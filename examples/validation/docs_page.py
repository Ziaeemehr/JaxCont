"""Generate ``docs/source/validation.md`` from the registry and the committed bundles.

  python3 -m examples.validation.docs_page          # rewrite the page
  python3 -m examples.validation.docs_page --check  # exit 1 if it is stale

Every registered case appears with its ``evidence_status``, the tools that
have a committed reference bundle (with the bundle's promotion verdict), and
its comparison page. Nothing on the page is typed by hand except the fixed
policy text below, so the page cannot drift from the registry.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from examples.validation.registry import load_registry

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REFERENCE = HERE / "reference"
PAGE = ROOT / "docs" / "source" / "validation.md"
TOOLS = {"matcont": "MatCont", "bifurcationkit": "BifurcationKit"}
# Comparison page per system (prefix of the canonical ID).
GALLERY = {"cubic": "plot_cubic", "vanderpol": "plot_vanderpol", "adaptx": "plot_adaptx",
           "radial": "plot_radial", "torbpc": "plot_torbpc", "lorenz84": "plot_lorenz84"}
GALLERY_BY_ID: dict[str, str] = {}


def bundles(case: dict) -> list[str]:
    """Committed bundles for one case: current v2 runs with their verdict, then legacy ones."""
    found = []
    for tool, label in TOOLS.items():
        for name in dict.fromkeys([case.get("canonical_id", case["id"]), case["id"]]):
            for directory in REFERENCE.glob(f"*/{tool}/{name}"):
                manifest = directory / "promotion-manifest.json"
                metadata = json.loads((directory / "metadata.json").read_text()) if (directory / "metadata.json").is_file() else {}
                if manifest.is_file():
                    verdict = json.loads(manifest.read_text())["verdict"]
                    version = (metadata.get("package_versions") or {}).get(label, "")
                    found.append(f"{label} {version}: {verdict}".replace("  ", " "))
                elif directory.is_dir():
                    found.append(f"{label}: legacy (v1) bundle")
    return found


def _page_link(case: dict) -> str:
    canonical = case.get("canonical_id", case["id"])
    page = GALLERY_BY_ID.get(canonical) or GALLERY.get(canonical.split(".")[0])
    return f"{{doc}}`auto_validation/{page}`" if page else "—"


HEADER = """# Validation against MatCont and BifurcationKit

<!-- Generated by `python3 -m examples.validation.docs_page` from
examples/validation/cases/cases.json and examples/validation/reference/.
Do not edit by hand. -->

Each case is a JaxCont computation compared with committed reference bundles
from MatCont 7.6 (MATLAB R2024a) and BifurcationKit 0.8.8 (Julia 1.13.3).
A case passes only when every comparison metric is within its declared
limit. The status column is the registry's `evidence_status`; each bundle
also records the verdict of its reviewed promotion. The comparison pages
under "Validation gallery" show the figures and tables for each system.

"""

POLICY = """
## Status meanings

- **PASS**: every metric of the case is within its limit against every
  committed bundle.
- **FAIL**: at least one metric is outside its limit. The failure is tracked
  and the case is not hidden.
- **PENDING**: the case runs, but its evidence is incomplete (a missing
  exporter, bundle or refined event), so no verdict is claimed.
- **UNSUPPORTED**: a MatCont capability JaxCont does not implement; listed so
  the boundary of the validation is explicit.

## Known limitations

Near a Hopf seed, periodic branches can report spurious folds at very small
amplitude; start periodic continuation from a seed of finite amplitude.


## Comparison policy

- Branches are compared over a declared window, on the first passage from
  the shared seed, against a well-conditioned monotone coordinate (or
  arclength near folds), with the denser series interpolated (PCHIP) at the
  sparser series' samples.
- Events are matched one-to-one by type and location. BifurcationKit's
  codimension-two curve events have native status `guess`; only the refined
  BT point (`lorenz84.bt-ft`) is compared.
- Floquet comparisons remove the trivial multiplier by flow-mode
  (eigenvector) alignment when the bundle supplies vectors, and record the
  nearest-to-`+1` fallback when it does not.
- Hopf coefficients use the MatCont/Kuznetsov convention with unit-norm `q`
  and denominator `2 * omega0`; the standard cubic Hopf has `l1 = -2`.
- Lorenz-84 runs use a Newton tolerance of `1e-12` and torBPC runs `1e-8`;
  both therefore require float64 (`jax.config.update("jax_enable_x64", True)`).

## Reproducing

The default test suite and the docs never call MATLAB or Julia; they read
the committed bundles. To re-run the comparisons:

```bash
JAX_ENABLE_X64=1 JAX_PLATFORMS=cpu python3 -m examples.validation.run_validation
```

Float64 is required for the Lorenz-84 and torBPC cases.

Regenerating a reference bundle is opt-in and needs `MATLAB_BIN` and
`MATCONT_ROOT` (MatCont) or `JULIA_BIN` (BifurcationKit); see
`examples/validation/README.md`.
"""


def render() -> str:
    cases = load_registry()["cases"]
    lines = ["| Case | What is checked | Status | Reference bundles | Comparison page |",
             "| --- | --- | --- | --- | --- |"]
    for case in cases:
        canonical = case.get("canonical_id", case["id"])
        evidence = "; ".join(bundles(case)) or "—"
        lines.append(f"| `{canonical}` | {case['title']} | {case['evidence_status']} | {evidence} | {_page_link(case)} |")
    counts = {}
    for case in cases:
        counts[case["evidence_status"]] = counts.get(case["evidence_status"], 0) + 1
    summary = ", ".join(f"{counts[status]} {status}" for status in ("PASS", "FAIL", "PENDING", "UNSUPPORTED") if status in counts)
    return HEADER + f"**{len(cases)} registered cases: {summary}.**\n\n" + "\n".join(lines) + "\n" + POLICY


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        stale = PAGE.read_text() != render()
        print("STALE  docs/source/validation.md" if stale else "OK  docs/source/validation.md")
        return int(stale)
    PAGE.write_text(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
